// 内置示例：手势演示（点击 / 滑动 / 长按 / 折线手势）
// 运行前：开启无障碍服务（脚本会自动等待并引导）
// 观察方式：悬浮条停止按钮可随时中断；运行日志实时输出到主界面「运行日志」面板

auto.waitFor(5000);                       // 等待无障碍服务开启，最多5秒
if (!auto.service) {                      // 超时仍未开启 → 提示并退出
    toastLog("请先开启无障碍服务");
    exit();
}

toastLog("手势演示开始");

log("1/4 坐标点击 click(400, 300)");
click(400, 300);
sleep(800);

log("2/4 滑动 swipe(700, 600 → 700, 250)");
swipe(700, 600, 700, 250, 400);
sleep(800);

log("3/4 长按 longClick(400, 300, 600)");
longClick(400, 300);
sleep(800);

log("4/4 折线手势 gesture(600, …)");
gesture(600, [300, 500], [450, 350], [600, 500]);
sleep(300);

toastLog("手势演示完成 ✓");
